export const FAILURE_CODES = [
  'INVALID_PAYLOAD',
  'REFERENCE_REQUIRED',
  'IDEMPOTENCY_PAYLOAD_MISMATCH',
  'IDEMPOTENCY_KEY_MISMATCH',
  'WALLET_ALREADY_EXISTS',
  'WALLET_NOT_FOUND',
  'WALLET_PLAYER_MISMATCH',
  'CURRENCY_MISMATCH',
  'INSUFFICIENT_FUNDS',
  'REVERSAL_INSUFFICIENT_FUNDS',
  'AMOUNT_OVERFLOW',
  'REFERENCE_NOT_FOUND',
  'REFERENCE_NOT_PROCESSED',
  'REFERENCE_KIND_NOT_ALLOWED',
  'REFERENCE_SCOPE_MISMATCH',
  'AMOUNT_MISMATCH',
  'REFERENCE_ALREADY_REVERSED',
  'PERSISTENT_STATE_CORRUPT',
] as const;

export type FailureCode = (typeof FAILURE_CODES)[number];

const PERSISTED_REJECTION_CODES = new Set<FailureCode>([
  'WALLET_NOT_FOUND',
  'WALLET_PLAYER_MISMATCH',
  'CURRENCY_MISMATCH',
  'INSUFFICIENT_FUNDS',
  'REVERSAL_INSUFFICIENT_FUNDS',
  'AMOUNT_OVERFLOW',
  'REFERENCE_NOT_FOUND',
  'REFERENCE_NOT_PROCESSED',
  'REFERENCE_KIND_NOT_ALLOWED',
  'REFERENCE_SCOPE_MISMATCH',
  'AMOUNT_MISMATCH',
  'REFERENCE_ALREADY_REVERSED',
]);

export function isPersistedRejection(code: FailureCode): boolean {
  return PERSISTED_REJECTION_CODES.has(code);
}
